def is_markdown_table_line(line):
    """Identify a Markdown table row, including rows with omitted outer pipes."""
    line = line.strip()
    if not line:
        return False
    if line.startswith(("- ", "* ", "+ ")) and "|" not in line:
        return False
    return line.count("|") >= 2 or (line.count("|") >= 1 and line.endswith("|"))


def parse_table_row(line):
    """Split a physical Markdown table row while preserving escaped pipes."""
    content = line.strip()
    if content.startswith("|"):
        content = content[1:]
    if content.endswith("|"):
        content = content[:-1]
    cells = re.split(r"(?<!\\)\|", content)
    return [cell.replace(r"\|", "|").strip() for cell in cells]


def is_separator_row(cells):
    return bool(cells) and all(
        re.fullmatch(r":?-{3,}:?", cell.replace(" ", "")) for cell in cells
    )


def _is_table_boundary(line):
    """Return True when a line clearly starts a new non-table block."""
    stripped = line.strip()
    if not stripped:
        return True
    if re.match(r"^#{1,4}\s+", stripped):
        return True
    if re.match(r"^(Limitations|Clinical Disclaimer|Clinical Information|"
                r"Recommended Next Steps|ICO Guidelines|Practical Summary)\b",
                stripped, re.IGNORECASE):
        return True
    return False


def _normalise_table_rows(lines):
    """
    Reconstruct logical rows from wrapped/malformed LLM Markdown tables.

    A line beginning with a pipe is treated as a new row when its first cell
    is populated. A continuation line without a leading pipe is aligned to
    the rightmost columns, which matches common wrapped LLM table output.
    """
    rows = []
    expected = None

    for raw in lines:
        line = raw.strip()
        if not line or "|" not in line:
            if rows and line:
                previous = rows[-1]
                target = next(
                    (i for i in range(len(previous) - 1, -1, -1)
                     if previous[i]),
                    None,
                )
                if target is not None:
                    previous[target] = (previous[target] + " " + line).strip()
            continue

        has_leading_pipe = line.startswith("|")
        cells = parse_table_row(line)
        if not cells or is_separator_row(cells):
            continue

        # Preserve empty cells in the middle, but remove optional outer empties.
        while cells and cells[0] == "" and has_leading_pipe:
            cells.pop(0)
        if line.endswith("|") and cells and cells[-1] == "":
            cells.pop()

        if not cells:
            continue

        if expected is None:
            expected = len(cells)
            rows.append(cells)
            continue

        if has_leading_pipe and cells[0]:
            # A populated first cell at the start of a pipe-prefixed line
            # marks a new row, even if the final column wraps onto later lines.
            row = cells[:expected] + [""] * max(0, expected - len(cells))
            rows.append(row)
            continue

        if len(cells) >= expected:
            row = cells[:expected]
            if len(cells) > expected:
                row[-1] = " | ".join(cells[expected - 1:])
            rows.append(row)
            continue

        # No leading pipe + fewer cells: continuation of the previous row.
        # Align to the rightmost columns (e.g. action + evidence columns).
        previous = rows[-1]
        if len(previous) < expected:
            previous.extend([""] * (expected - len(previous)))
        offset = expected - len(cells)
        for cell_index, value in enumerate(cells):
            if value:
                target = offset + cell_index
                previous[target] = (previous[target] + " " + value).strip()

    if not rows:
        return []

    column_count = max(len(row) for row in rows)
    return [row + [""] * (column_count - len(row)) for row in rows]


def render_markdown_table(lines, styles):
    """Convert a reconstructed Markdown table into a styled ReportLab Table."""
    rows_data = _normalise_table_rows(lines)
    if not rows_data:
        return []

    column_count = max(len(row) for row in rows_data)
    if column_count < 2:
        # A one-column pipe fragment is not a reliable table.
        return [
            Paragraph(inline_markdown(" ".join(row)), styles["body"])
            for row in rows_data if any(row)
        ]

    rows = []
    for row in rows_data:
        rows.append([
            Paragraph(inline_markdown(cell), styles["small"])
            for cell in row
        ])

    usable_width = A4[0] - 40 * mm
    col_widths = [usable_width / column_count] * column_count
    table = Table(
        rows, colWidths=col_widths, repeatRows=1, hAlign="LEFT",
        splitByRow=1, spaceAfter=3 * mm,
    )
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#24476B")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), FONT_NAMES["bold"]),
        ("GRID", (0, 0), (-1, -1), 0.45, colors.HexColor("#CBD5E1")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1),
         [colors.white, colors.HexColor("#F2F6FA")]),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 5),
        ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    return [table, Spacer(1, 3 * mm)]


def _looks_like_table_continuation(line):
    """Recognize wrapped table-cell text and bullet fragments."""
    stripped = line.strip()
    if not stripped:
        return False
    if re.match(r"^#{1,4}\s+", stripped):
        return False
    if re.match(r"^(Limitations|Clinical Disclaimer|Clinical Information|"
                r"Recommended Next Steps|ICO Guidelines|Practical Summary)\b",
                stripped, re.IGNORECASE):
        return False
    # Continuation lines are commonly indented or contain table separators.
    return (
        "|" in stripped
        or line.startswith((" ", "\t"))
        or stripped.startswith(("- ", "* ", "+ "))
        or stripped.endswith((")", ".", ";", ","))
    )


def _consume_table_block(lines, start_index):
    """
    Consume a table and its wrapped continuation lines.

    Blank lines are tolerated only when the next non-empty line still looks
    like part of the table. A new heading or normal paragraph ends the block.
    """
    collected = []
    index = start_index
    saw_table_row = False

    while index < len(lines):
        line = lines[index]
        stripped = line.strip()

        if not stripped:
            lookahead = index + 1
            while lookahead < len(lines) and not lines[lookahead].strip():
                lookahead += 1
            if lookahead >= len(lines):
                index = lookahead
                break
            if saw_table_row and _looks_like_table_continuation(lines[lookahead]):
                index = lookahead
                continue
            break

        if collected and _is_table_boundary(stripped):
            break

        if "|" in stripped:
            collected.append(stripped)
            saw_table_row = True
            index += 1
            continue

        if saw_table_row and _looks_like_table_continuation(line):
            collected.append(line)
            index += 1
            continue

        if saw_table_row:
            break

        index += 1

    return collected, index


def render_markdown(content, styles, patient_facing=False):
    """Render Markdown paragraphs, lists, headings, and multiline tables."""
    story = []
    content = clean_text(content)
    if not content:
        return story

    lines = content.splitlines()
    paragraph_buffer = []

    def flush_paragraph():
        if paragraph_buffer:
            paragraph_text = " ".join(part.strip() for part in paragraph_buffer).strip()
            if paragraph_text:
                story.append(Paragraph(inline_markdown(paragraph_text), styles["body"]))
            paragraph_buffer.clear()

    index = 0
    while index < len(lines):
        raw_line = lines[index]
        line = raw_line.strip()

        if not line:
            flush_paragraph()
            index += 1
            continue

        if is_markdown_table_line(line):
            flush_paragraph()
            table_lines, next_index = _consume_table_block(lines, index)
            if table_lines:
                rendered = render_markdown_table(table_lines, styles)
                if rendered:
                    story.extend(rendered)
                else:
                    # Safe fallback: show the source as readable text, not raw
                    # pipe syntax or a malformed ReportLab table.
                    fallback = " ".join(
                        cell for row in _normalise_table_rows(table_lines)
                        for cell in row if cell
                    )
                    if fallback:
                        story.append(Paragraph(
                            inline_markdown(fallback), styles["body"]
                        ))
                index = max(next_index, index + 1)
                continue

        if line in {"---", "***", "___"}:
            flush_paragraph()
            story.append(Spacer(1, 2 * mm))
            index += 1
            continue

        heading_match = re.match(r"^(#{1,4})\s+(.+)$", line)
        if heading_match:
            flush_paragraph()
            heading_level = len(heading_match.group(1))
            heading_text = heading_match.group(2).strip()
            normalized_heading = re.sub(
                r"[^a-z0-9]+", " ", heading_text.lower()
            ).strip()
            redundant_headings = {
                "structured summary for mild dr",
                "structured summary for mild diabetic retinopathy",
                "practical summary for clinicians",
                "clinical information",
                "recommended next steps",
                "ico guidelines",
                "evidence sources and references",
            }
            if normalized_heading in redundant_headings:
                index += 1
                continue
            if patient_facing and re.search(
                r"clinician|evidence sources|ico guidelines",
                heading_text, re.IGNORECASE,
            ):
                index += 1
                continue
            style = styles["heading"] if heading_level <= 2 else styles["subheading"]
            story.append(Paragraph(inline_markdown(heading_text), style))
            index += 1
            continue

        ordered_match = re.match(r"^(\d+)[.)]\s+(.+)$", line)
        if ordered_match:
            flush_paragraph()
            number, item = ordered_match.groups()
            story.append(Paragraph(
                f"{number}. {inline_markdown(item)}", styles["bullet"]
            ))
            index += 1
            continue

        bullet_match = re.match(r"^[-*+]\s+(.+)$", line)
        if bullet_match:
            flush_paragraph()
            story.append(Paragraph(
                f"- {inline_markdown(bullet_match.group(1))}",
                styles["bullet"],
            ))
            index += 1
            continue

        if re.fullmatch(r"\d{1,2}[.)]?", line):
            index += 1
            continue

        # Any leftover pipe fragment is rendered as clean text, never raw pipes.
        if "|" in line:
            cleaned = " ".join(part.strip() for part in line.split("|") if part.strip())
            if cleaned:
                paragraph_buffer.append(cleaned)
            index += 1
            continue

        paragraph_buffer.append(line)
        index += 1

    flush_paragraph()
    return story


def add_image(story, image_path, caption, styles):
    if not image_path:
        return
    path = Path(image_path)
    if not path.is_file():
        logger.warning("Report image unavailable: %s", path)
        return
    try:
        with PILImage.open(path) as source:
            width, height = source.size
        if width <= 0 or height <= 0:
            return

        max_width, max_height = 150 * mm, 82 * mm
        scale = min(max_width / width, max_height / height, 1.0)
        pdf_image = Image(
            str(path), width=width * scale, height=height * scale,
            hAlign="CENTER",
        )
        story.append(KeepTogether([
            pdf_image,
            Spacer(1, 2 * mm),
            Paragraph(escape(clean_text(caption)), styles["caption"]),
            Spacer(1, 4 * mm),
        ]))
    except Exception:
        logger.exception("Could not add image to PDF: %s", path)


def normalise_probabilities(probabilities):
    if not isinstance(probabilities, dict):
        return {}
    result = {}
    for class_name in CLASS_ORDER:
        if class_name not in probabilities:
            continue
        try:
            value = float(probabilities[class_name])
        except (TypeError, ValueError):
            continue
        if not 0 <= value <= 100:
            continue
        if value <= 1:
            value *= 100
        result[class_name] = value
    return result


def _safe_paragraph(value, style):
    return Paragraph(escape(clean_text(value)), style)



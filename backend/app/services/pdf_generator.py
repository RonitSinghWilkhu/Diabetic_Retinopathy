def generate_patient_report(report_data: dict) -> bytes:
    """Generate the patient report followed by the clinician appendix."""
    if not isinstance(report_data, dict):
        raise TypeError("report_data must be a dictionary.")

    predicted_class = report_data.get("predicted_class")
    if not predicted_class:
        raise ValueError("Predicted DR class is required.")

    styles = create_styles()
    output = BytesIO()
    document = SimpleDocTemplate(
        output,
        pagesize=A4,
        rightMargin=20 * mm,
        leftMargin=20 * mm,
        topMargin=18 * mm,
        bottomMargin=23 * mm,
        title="Diabetic Retinopathy Screening Report",
        author="RetinaAI",
    )
    story = []

    # Patient summary.
    story.append(Paragraph(
        "DIABETIC RETINOPATHY SCREENING REPORT", styles["title"]
    ))
    generated = datetime.now().astimezone().strftime("%d %B %Y, %I:%M %p %Z")
    story.append(Paragraph(f"<b>Generated:</b> {escape(generated)}", styles["body"]))

    if report_data.get("analysis_id") is not None:
        story.append(Paragraph(
            f"<b>Analysis ID:</b> {escape(str(report_data['analysis_id']))}",
            styles["body"],
        ))
    if report_data.get("patient_name"):
        story.append(Paragraph(
            f"<b>Patient:</b> {escape(clean_text(report_data['patient_name']))}",
            styles["body"],
        ))

    story.append(Paragraph("PATIENT SUMMARY", styles["section"]))
    story.append(Paragraph("Uploaded Retinal Image", styles["heading"]))
    add_image(
        story, report_data.get("original_image_path"),
        "Original uploaded retinal photograph", styles,
    )

    story.append(Paragraph("Predicted DR Severity", styles["heading"]))
    class_label = CLASS_LABELS.get(
        predicted_class, str(predicted_class).replace("_", " ")
    )
    story.append(Paragraph(f"<b>{escape(class_label)}</b>", styles["body"]))

    confidence = report_data.get("confidence")
    if confidence is not None:
        try:
            confidence = float(confidence)
            if 0 <= confidence <= 1:
                confidence *= 100
            if 0 <= confidence <= 100:
                story.append(Paragraph(
                    f"Model confidence: {confidence:.2f}%", styles["body"]
                ))
        except (TypeError, ValueError):
            logger.warning("Invalid confidence value: %r", confidence)

    if report_data.get("model_name"):
        story.append(Paragraph(
            f"Model: {escape(clean_text(report_data['model_name']))}",
            styles["body"],
        ))

    add_probability_table(
        story, normalise_probabilities(report_data.get("probabilities", {})),
        styles,
    )

    story.append(Paragraph("Grad-CAM Visualization", styles["heading"]))
    story.append(Paragraph(
        "These visualizations show image regions that influenced the model "
        "prediction. They do not confirm the presence or exact location of "
        "retinal lesions.",
        styles["body"],
    ))
    add_image(
        story, report_data.get("gradcam_heatmap_path"), "Grad-CAM heatmap", styles
    )
    add_image(
        story, report_data.get("gradcam_overlay_path"), "Grad-CAM overlay", styles
    )

    story.append(Paragraph("Understanding Your Result", styles["heading"]))
    story.extend(render_markdown(
        report_data.get("explanation", ""), styles, patient_facing=True
    ))

    if report_data.get("patient_meaning"):
        story.append(Paragraph("What Your DR Class Means", styles["heading"]))
        story.extend(render_markdown(
            report_data["patient_meaning"], styles, patient_facing=True
        ))

    prevention = report_data.get("prevention", [])
    if isinstance(prevention, str):
        prevention = [prevention]
    if prevention:
        story.append(Paragraph("Prevention Guidance", styles["heading"]))
        for item in prevention:
            story.extend(render_markdown(item, styles, patient_facing=True))

    story.append(Paragraph("Limitations", styles["heading"]))
    limitations = [
        "The model may produce incorrect classifications.",
        "Model probabilities are not equivalent to clinical certainty.",
        "Grad-CAM visualizations show model sensitivity, not confirmed disease locations.",
        "Image quality and camera differences may affect predictions.",
        "This report does not replace a clinical retinal examination.",
    ]
    for limitation in limitations:
        story.append(Paragraph(
            f"- {escape(limitation)}", styles["bullet"]
        ))

    story.append(KeepTogether([
        Paragraph("Clinical Disclaimer", styles["heading"]),
        Paragraph(escape(DISCLAIMER), styles["body"]),
    ]))

    # Clinician appendix.
    story.append(PageBreak())
    story.append(Paragraph("CLINICIAN APPENDIX", styles["section"]))

    story.append(Paragraph("Clinical Information", styles["heading"]))
    story.extend(render_markdown(
        report_data.get("clinical_information", ""), styles
    ))

    next_steps = report_data.get("next_steps", [])
    if isinstance(next_steps, str):
        next_steps = [next_steps]
    if next_steps:
        story.append(Paragraph("Recommended Next Steps", styles["heading"]))
        for item in next_steps:
            story.extend(render_markdown(item, styles))

    ico_guidelines = report_data.get("ico_guidelines", "")
    if ico_guidelines:
        story.append(Paragraph("ICO Guidelines", styles["heading"]))
        story.extend(render_markdown(ico_guidelines, styles))

    practical_summary = report_data.get("practical_summary", "")
    if practical_summary:
        story.append(Paragraph(
            "Practical Summary for Clinicians", styles["heading"]
        ))
        story.extend(render_markdown(practical_summary, styles))

    # Keep evidence references short and bibliographic.
    story.append(PageBreak())
    add_evidence_references(story, report_data.get("evidence", []), styles)

    document.build(
        story,
        onFirstPage=draw_page_footer,
        onLaterPages=draw_page_footer,
    )
    pdf_bytes = output.getvalue()
    if not pdf_bytes.startswith(b"%PDF"):
        raise ValueError("Generated output is not a valid PDF.")
    return pdf_bytes
def _font_candidates(filename):
    """Return likely locations for the DejaVu Sans TTF files."""
    here = Path(__file__).resolve()
    backend_root = here.parents[2]
    candidates = [
        backend_root / "app" / "assets" / "fonts" / filename,
        backend_root / "assets" / "fonts" / filename,
        Path("C:/Windows/Fonts") / filename,
        Path("/usr/share/fonts/truetype/dejavu") / filename,
        Path("/usr/share/fonts/dejavu") / filename,
        Path("/usr/local/share/fonts") / filename,
    ]
    return candidates


def register_report_fonts():
    """
    Register DejaVu Sans TTF fonts.

    Recommended project location:
      backend/app/assets/fonts/DejaVuSans.ttf
      backend/app/assets/fonts/DejaVuSans-Bold.ttf
      backend/app/assets/fonts/DejaVuSans-Oblique.ttf
      backend/app/assets/fonts/DejaVuSans-BoldOblique.ttf

    DejaVu Sans is embedded in the PDF by ReportLab, so readers do not need
    the font installed on their machines.
    """
    font_files = {
        "regular": "DejaVuSans.ttf",
        "bold": "DejaVuSans-Bold.ttf",
        "oblique": "DejaVuSans-Oblique.ttf",
        "bold_oblique": "DejaVuSans-BoldOblique.ttf",
    }

    for key, filename in font_files.items():
        font_name = FONT_NAMES[key]
        if font_name in pdfmetrics.getRegisteredFontNames():
            continue

        font_path = next((p for p in _font_candidates(filename) if p.is_file()), None)
        if font_path is None:
            raise FileNotFoundError(
                f"Cannot find {filename}. Put the DejaVu Sans font files in "
                "backend/app/assets/fonts/ and retry."
            )
        pdfmetrics.registerFont(TTFont(font_name, str(font_path)))

    # Tell ReportLab which face to use for <b> and <i> tags.
    pdfmetrics.registerFontFamily(
        FONT_NAMES["regular"],
        normal=FONT_NAMES["regular"],
        bold=FONT_NAMES["bold"],
        italic=FONT_NAMES["oblique"],
        boldItalic=FONT_NAMES["bold_oblique"],
    )


def clean_text(value):
    """Normalize text without altering ordinary words or valid list numbering."""
    text = str(value or "")

    # Convert common HTML breaks and list tags before ReportLab parsing.
    text = re.sub(r"(?i)<\s*br\s*/?\s*>", "\n", text)
    text = re.sub(r"(?i)</\s*p\s*>", "\n", text)
    text = re.sub(r"(?i)<\s*p(?:\s+[^>]*)?>", "", text)
    text = re.sub(r"(?i)<\s*li(?:\s+[^>]*)?>", "- ", text)
    text = re.sub(r"(?i)</\s*li\s*>", "\n", text)
    text = re.sub(r"(?i)<\s*/?\s*ul(?:\s+[^>]*)?>", "\n", text)
    text = re.sub(r"(?i)<\s*/?\s*ol(?:\s+[^>]*)?>", "\n", text)

    replacements = {
        "\u25a0": "", "\u25aa": "", "\uf0b7": "-",
        "\u2010": "-", "\u2011": "-", "\u2012": "-",
        "\u2013": "-", "\u2014": "-", "\u2212": "-",
        "\u00ad": "", "\u00a0": " ", "\u2022": "-",
        "\ufb00": "ff", "\ufb01": "fi", "\ufb02": "fl",
        "\ufb03": "ffi", "\ufb04": "ffl",
    }
    for old, new in replacements.items():
        text = text.replace(old, new)

    # Normalize citations, including black-square and line-range variants.
    pattern = re.compile(
        r"(?P<space>\s*)[\[\]■□]*Evidence\s+(\d+)"
        r"(?:\s*[†‡]\s*L?\d+(?:\s*[-–]\s*L?\d+)?)?"
        r"[\[\]■□]*(?P<after>\s*)",
        flags=re.IGNORECASE,
    )
    text = pattern.sub(
        lambda m: f"{m.group('space')}[Evidence {m.group(2)}]{m.group('after')}",
        text,
    )

    # Convert malformed grouped citations to separate valid citations.
    text = re.sub(
        r"\[Evidence\s+(\d+)\]\s*,\s*(\d+(?:\s*,\s*\d+)+)\s*\]",
        lambda m: f"[Evidence {m.group(1)}] " + " ".join(
            f"[Evidence {n.strip()}]" for n in m.group(2).split(",")
        ),
        text,
        flags=re.IGNORECASE,
    )
    text = re.sub(
        r"\[Evidence\s+(\d+)\]\s*,\s*(\d+)\s*,\s*(\d+)\]",
        r"[Evidence \1] [Evidence \2] [Evidence \3]",
        text,
        flags=re.IGNORECASE,
    )

    # Fix a lowercase-L / capital-I typo at the start of Introduction.
    text = re.sub(
        r"(?im)^(\s*)[lI|]\s*[.)]\s*(Introduction\b)",
        r"\g<1>1. \2",
        text,
    )

    # Remove a dangling number on its own line, not valid "4. Heading" items.
    text = re.sub(r"(?m)^\s*\d{1,2}\s*$", "", text)

    text = "".join(ch for ch in text if ch in "\n\t" or ord(ch) >= 32)
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r"\n[ \t]+", "\n", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def inline_markdown(value):
    """Convert safe inline Markdown to ReportLab paragraph markup."""
    text = clean_text(value)

    # Temporarily protect intended line breaks from XML escaping.
    text = text.replace("\n", " __REPORTLAB_BR__ ")
    text = escape(text)

    # Inline code.
    text = re.sub(r"`([^`]+)`", r"<font name='Courier'>\1</font>", text)

    # Bold+italic, bold, then italic. Avoid consuming the other markers.
    text = re.sub(r"\*\*\*(.+?)\*\*\*", r"<b><i>\1</i></b>", text)
    text = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", text)
    text = re.sub(r"(?<!\*)\*([^*\n]+?)\*(?!\*)", r"<i>\1</i>", text)
    text = re.sub(r"__(.+?)__", r"<b>\1</b>", text)
    text = re.sub(r"(?<!_)_([^_\n]+?)_(?!_)", r"<i>\1</i>", text)

    # Restore ReportLab line-break tags after escaping raw HTML.
    text = text.replace("__REPORTLAB_BR__", "<br/>")
    return text



def add_evidence_references(story, evidence, styles):
    """Render bibliographic metadata only; never render extracted passages."""
    story.append(Paragraph("Evidence Sources and References", styles["heading"]))
    if not evidence:
        story.append(Paragraph(
            "No supporting evidence references were supplied.", styles["body"]
        ))
        return

    seen = set()
    number = 1
    for item in evidence:
        if not isinstance(item, dict):
            continue
        source = clean_text(item.get("source") or "Unknown source")
        pages = item.get("pages") or []
        if not isinstance(pages, (list, tuple, set)):
            pages = [pages]
        page_values = sorted({str(page).strip() for page in pages if str(page).strip()})
        key = (source, tuple(page_values))
        if key in seen:
            continue
        seen.add(key)

        page_text = ", ".join(page_values) if page_values else "Not specified"
        story.append(Paragraph(
            f"{number}. <b>{escape(source)}</b> - Page(s): {escape(page_text)}",
            styles["body"],
        ))
        number += 1


